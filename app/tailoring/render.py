_TOKEN_RE = re.compile(r"[a-z0-9][a-z0-9+#]*(?:[.\-/][a-z0-9+#]+)*")
_NUMERIC_RE = re.compile(r"[\d+.,%/\-]+")


def _terms(text: str) -> set[str]:
    """Lowercase words + adjacent-word bigrams, minus stopwords and numbers."""
    toks = [t for t in _TOKEN_RE.findall((text or "").lower())]
    keep = [t if (t not in _STOPWORDS and not _NUMERIC_RE.fullmatch(t)
                  and (len(t) > 1 or t in ("c", "r"))) else None for t in toks]
    terms = {t for t in keep if t}
    for a, b in zip(keep, keep[1:]):
        if a and b:
            terms.add(f"{a} {b}")
    return terms


def _is_trim_section(heading: str) -> bool:
    return bool(_TRIM_SECTION_RE.search(heading)) and not _PROTECTED_SECTION_RE.search(heading)


_DATE = (r"(?:(?:jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)[a-z]*\.?,?\s*|\d{1,2}/)?"
         r"(?:19|20)\d{2}")
_DATE_RANGE = (rf"{_DATE}\s*(?:-|\u2013|\u2014|to|until)\s*"
               rf"(?:{_DATE}|present|current|now|today|date)")
_DATE_RANGE_RE = re.compile(_DATE_RANGE, re.I)
_ENDS_WITH_DATE_RANGE_RE = re.compile(rf"{_DATE_RANGE}\)?\s*$", re.I)


def _is_role_line(b: Block) -> bool:
    """A role header written as a bullet: "- **Engineer** | Acme | 2020 - 2024",
    "- **Engineer, Acme**", "- Engineer, Acme, Jan 2020 - Present",
    "- **Engineer**, Acme, 2020 - 2024, Remote". Never trimmed, and it starts
    a new role like any other non-bullet line. Generous on purpose: an
    achievement bullet read as a header only stays on the page, while a
    header read as a bullet could be removed."""
    if b.kind != "bullet":
        return False
    body = b.raw[2:].strip()
    if body.startswith("**") and "|" in body:
        return True
    if b.runs and all(r.bold for r in b.runs if r.text.strip()):
        return True
    text = b.text
    if not _DATE_RANGE_RE.search(text):
        return False
    return bool(_ENDS_WITH_DATE_RANGE_RE.search(text) or "|" in text
                or body.startswith("**")
                or (text.count(",") >= 2 and len(text) <= 100))


def _roles(blocks: list[Block]) -> list[list[Block]]:
    """Runs of trimmable bullets, document order, trimmable sections only.

    Any line in such a section that is not a plain bullet - a "### "
    subhead, a "**Engineer** | Acme | 2023 - 2025" line, a plain "Engineer,
    Acme, 2023 - 2025" line, a bulleted role header - ends the current run;
    consecutive such lines (company line + title line) start one run.
    Grouping by run rather than by recognising role lines means a role
    header in an unexpected shape can never merge two roles into one, where
    trimming could empty one of them.
    """
    roles: list[list[Block]] = []
    in_trim = False
    cur: Optional[list[Block]] = None
    for b in blocks:
        if b.kind in ("section", "name"):
            in_trim = b.kind == "section" and _is_trim_section(b.text)
            cur = None
            continue
        if not in_trim:
            continue
        if b.kind != "bullet" or _is_role_line(b):
            if cur is None or cur:
                cur = []
                roles.append(cur)
            continue
        if cur is None:
            cur = []
            roles.append(cur)
        cur.append(b)
    return [r for r in roles if r]


def _trim_order(blocks: list[Block], jd_text: str) -> list[Block]:
    """Removable bullets, first to go first: fewest job-description terms,
    then the later (older) role, then the longer bullet. Each run keeps its
    most relevant bullet (ties: the first, which writers lead with)."""
    jd = _terms(jd_text)
    scored: list[tuple[int, int, int, int, Block]] = []
    for gi, role in enumerate(_roles(blocks)):
        if len(role) < 2:
            continue
        rel = {id(b): len(_terms(b.text) & jd) for b in role}
        keep = max(role, key=lambda b: (rel[id(b)], -b.line_no))
        for b in role:
            if b is not keep:
                scored.append((rel[id(b)], -gi, -len(b.text), -b.line_no, b))
    scored.sort(key=lambda s: s[:4])
    return [s[4] for s in scored]


def trim_candidates(md: str, jd_text: str = "") -> list[str]:
    """Bullet texts in the order ``fit_one_page`` would remove them."""
    return [b.text for b in _trim_order(parse_md(md), jd_text)]


@dataclass
class FitResult:
    md: str                    # the (possibly trimmed) markdown - write the DOCX from this
    pdf_bytes: bytes
    tier_index: int
    pages: int                 # read back from the PDF bytes with pypdf
    trimmed: list[str] = field(default_factory=list)  # removed bullet texts, in order
    # characters the PDF prints as "?" (no glyph in the bundled font); when
    # non-empty the PDF misstates the resume and must not be delivered
    undrawable: list[str] = field(default_factory=list)

    @property
    def tier(self) -> Tier:
        return TIERS[self.tier_index]

    @property
    def one_page(self) -> bool:
        return self.pages == 1


def _drop_lines(md: str, line_nos: set[int]) -> str:
    if not line_nos:
        return md
    lines = md.splitlines(keepends=True)
    return "".join(ln for i, ln in enumerate(lines) if i not in line_nos)


def fit_one_page(md: str, *, jd_text: str = "", author: str = "", title: str = "",
                 max_renders: int = 8) -> FitResult:
    """The densest-needed layout that puts the resume on ONE page.

    1. Tiers T0..T3 in order; the first that paginates to one page with
       ``word_reserve_pt`` to spare wins.
    2. Still too long at T3: remove bullets one at a time in
       ``trim_candidates`` order (fewest job-description terms first, then
       the older role, then the longer bullet; each run of bullets keeps one)
       until it fits or nothing removable is left. Removal only - no line is
       added or reworded.

    Every attempt is laid out by the same pagination ``render_pdf`` draws
    with, so trying a tier or a trim costs arithmetic, not a PDF.
    ``max_renders`` bounds the PDFs actually produced: one normally; more only
    if pypdf disagreed with the layout (it should not), in which case trimming
    continues against real renders.
    """
    blocks = parse_md(md)
    cache = _LayoutCache()

    def fits(kept: list[Block], t: Tier) -> bool:
        return len(_paginate(cache.lay(kept, t), t, word_reserve_pt(t))) == 1

    tier_index = len(TIERS) - 1
    for i, t in enumerate(TIERS):
        if fits(blocks, t):
            tier_index = i
            break
    tier = TIERS[tier_index]

    removed: list[Block] = []
    kept = list(blocks)
    order = _trim_order(blocks, jd_text)
    if not fits(kept, tier):
        for b in order:
            removed.append(b)
            kept = [k for k in kept if k is not b]
            if fits(kept, tier):
                break
        else:
            # Nothing removable is left: the sections that hold the bullets
            # are not ones fitting may touch (headings outside
            # _TRIM_SECTION_RE), or every role is down to one bullet.
            log.warning("resume fit: no removable bullet left at %s (%d removable of %d "
                        "blocks) - the layout may run past one page",
                        tier.name, len(order), len(blocks))

    renders = 0
    while True:
        out_md = _drop_lines(md, {b.line_no for b in removed})
        pdf = _draw(_paginate(cache.lay(kept, tier), tier), tier, author=author, title=title)
        renders += 1
        pages = page_count(pdf)
        remaining = [b for b in order if b not in removed]
        if pages == 1 or not remaining or renders >= max(1, max_renders):
            break
        log.warning("resume fit: layout said 1 page, pypdf read %d - trimming further", pages)
        removed.append(remaining[0])
        kept = [k for k in kept if k is not remaining[0]]

    if removed:
        log.info("resume fit: %s with %d bullet(s) trimmed -> %d page(s)",
                 tier.name, len(removed), pages)
    if pages > 1:
        log.warning("resume fit: %d pages at %s after %d trim(s)", pages, tier.name, len(removed))
    return FitResult(md=out_md, pdf_bytes=pdf, tier_index=tier_index, pages=pages,
                     trimmed=[b.text for b in removed],
                     undrawable=undrawable_chars("\n".join(b.text for b in kept)))


