def _calibri(rpr_parent) -> None:
    """Point a style's (or docDefaults') rFonts at Calibri for real: an
    ``asciiTheme`` attribute outranks ``ascii``, and the template's theme
    resolves the minor font to Cambria."""
    from docx.oxml.ns import qn

    rpr = rpr_parent.get_or_add_rPr() if hasattr(rpr_parent, "get_or_add_rPr") else rpr_parent
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = rpr.makeelement(qn("w:rFonts"), {})
        rpr.insert(0, rfonts)
    for a in ("w:asciiTheme", "w:hAnsiTheme", "w:cstheme"):
        rfonts.attrib.pop(qn(a), None)
    for a in ("w:ascii", "w:hAnsi", "w:cs"):
        rfonts.set(qn(a), "Calibri")


def _apply_tier_styles(doc, tier: Tier) -> None:
    """``tailor._set_ats_safe_styles`` with the tier's numbers (T0 = identical
    sizes/margins/spacing), plus: explicit line spacing, Calibri that is not
    overridden by the theme, and the thin rule under section headings that
    the PDF draws."""
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    from docx.shared import Inches, Pt, RGBColor

    for sec in doc.sections:
        sec.page_width = Inches(8.5)
        sec.page_height = Inches(11)
        sec.top_margin = sec.bottom_margin = Inches(tier.margin_in)
        sec.left_margin = sec.right_margin = Inches(tier.margin_in)

    defaults = doc.styles.element.find(qn("w:docDefaults"))
    if defaults is not None:
        rpr = defaults.find(qn("w:rPrDefault") + "/" + qn("w:rPr"))
        if rpr is not None:
            _calibri(rpr)

    normal = doc.styles["Normal"]
    normal.font.name = "Calibri"
    normal.font.size = Pt(tier.body_pt)
    pf = normal.paragraph_format
    pf.space_before = Pt(0)
    pf.space_after = Pt(tier.para_after_pt)
    pf.line_spacing = tier.line_spacing  # a float = Word "multiple" (lineRule auto)
    _calibri(normal.element)

    def heading(name: str, size: float, before: float, after: float):
        st = doc.styles[name]
        st.font.name = "Calibri"
        st.font.size = Pt(size)
        st.font.bold = True
        st.font.color.rgb = RGBColor(*_DARK)
        st.paragraph_format.space_before = Pt(before)
        st.paragraph_format.space_after = Pt(after)
        _calibri(st.element)
        return st

    heading("Heading 1", tier.h1_pt, 0.0, tier.h1_after_pt)
    h2 = heading("Heading 2", tier.h2_pt, tier.h2_before_pt, tier.h2_after_pt)
    heading("Heading 3", tier.h3_pt, tier.h3_before_pt, tier.h3_after_pt)

    ppr = h2.element.get_or_add_pPr()
    if ppr.find(qn("w:pBdr")) is None:
        pbdr = OxmlElement("w:pBdr")
        bottom = OxmlElement("w:bottom")
        bottom.set(qn("w:val"), "single")
        bottom.set(qn("w:sz"), str(int(_RULE_W_PT * 8)))
        bottom.set(qn("w:space"), str(int(_RULE_GAP_PT)))
        bottom.set(qn("w:color"), "%02X%02X%02X" % _RULE)
        pbdr.append(bottom)
        ppr.insert_element_before(
            pbdr, "w:shd", "w:tabs", "w:suppressAutoHyphens", "w:kinsoku", "w:wordWrap",
            "w:overflowPunct", "w:topLinePunct", "w:autoSpaceDE", "w:autoSpaceDN",
            "w:bidi", "w:adjustRightInd", "w:snapToGrid", "w:spacing", "w:ind",
            "w:contextualSpacing", "w:mirrorIndents", "w:suppressOverlap", "w:jc",
            "w:textDirection", "w:textAlignment", "w:textboxTightWrap",
            "w:outlineLvl", "w:divId", "w:cnfStyle", "w:rPr", "w:sectPr", "w:pPrChange")

    lb = doc.styles["List Bullet"]
    lb.font.name = "Calibri"
    lb.font.size = Pt(tier.body_pt)
    lb.paragraph_format.space_after = Pt(tier.bullet_after_pt)
    lb.paragraph_format.left_indent = Inches(tier.bullet_indent_in)
    lb.paragraph_format.first_line_indent = Inches(-tier.bullet_indent_in)
    _calibri(lb.element)


def _docx_text(s: str) -> str:
    return _XML_BAD_RE.sub("", s.replace("\t", " "))


def write_docx(md: str, path: Union[str, Path], tier: Union[Tier, int] = 0, *,
               author: str = "", title: str = "") -> Path:
    """Write the markdown resume as an ATS-safe .docx at ``tier`` - the same
    paragraphs, sizes and margins the PDF uses - then scrub its metadata.

    Single column; standard Heading 1/2/3, List Bullet and Normal styles; no
    tables, text boxes, headers or footers.
    """
    from docx import Document

    t = _tier(tier)
    doc = Document()
    _apply_tier_styles(doc, t)
    for b in parse_md(md):
        p = doc.add_paragraph(style=_DOCX_STYLE.get(b.kind, "Normal"))
        for r in b.runs:
            run = p.add_run(_docx_text(r.text))
            if r.bold:
                run.bold = True
            if r.italic:
                run.italic = True
    buf = io.BytesIO()
    doc.save(buf)
    out = Path(path)
    _atomic_write(out, _scrub_docx_bytes(buf.getvalue(), author=author, title=title))
    return out


def _atomic_write(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=str(path.parent), prefix=".tmp-", suffix=path.suffix)
    try:
        with os.fdopen(fd, "wb") as fh:
            fh.write(data)
        os.chmod(tmp, 0o644)  # mkstemp creates 0600; match a plain write
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


