"""One-page resume rendering: PDF + Word from the SAME markdown, same layout.

The owner's rules for every tailored resume: ONE page, delivered as a PDF and
a matching Word .docx, named ``First_Last_Resume``, with no trace of the
generator in the file metadata.

How the pieces fit:

* ``parse_md`` reads the tailored markdown with exactly the line mapping
  ``tailor._md_to_docx`` uses ("# " = name / Heading 1, "## " = section /
  Heading 2, "### " = subhead / Heading 3, "- "/"* " = List Bullet, anything
  else = Normal; ``**bold**`` / ``*italic*`` become runs), so the PDF and the
  DOCX say the same thing in the same order.
* ``TIERS`` are layouts from the current Word look (T0: 11pt Calibri, 0.75in,
  Word's 1.15 line spacing) down to T3 (9.5pt, 0.5in, single spacing). Nothing
  goes below 9.5pt body or 0.5in margins - readability and ATS parsing.
* The PDF is laid out by THIS module (greedy word wrap over the glyph advance
  widths of the bundled Carlito font, which is metric-compatible with Calibri,
  then one ``text()`` per run per line), so "will it fit on one page?" is
  plain arithmetic: ``fit_one_page`` can try every tier and every trim
  without producing a PDF, and the single PDF it does produce paginates by the
  same function that answered. ``page_count`` re-checks the bytes with pypdf.
* A layout counts as fitting only with about one body line to spare: Word
  breaks lines with its own engine, and a resume that fills the PDF page to
  the last point can spill onto a second page in Word.
* When even T3 is two pages, ``fit_one_page`` REMOVES whole bullets - least
  relevant to the job description first, then the older role, then the
  longer bullet - and never adds or rewrites a word: every line was already
  fact-checked by the tailoring pipeline. Header, headings, role lines
  (bulleted ones included), summary, skills and education are never touched,
  and every run of bullets under a role line keeps at least one.
* ``render_pdf`` / ``write_docx`` stamp the candidate as author, leave
  creator/producer empty and scrub the generator defaults (fpdf2's subset
  tag, python-docx's "generated by python-docx" core properties, its static
  app.xml, template thumbnail, bibliography part and the revision ids every
  python-docx file shares).
* ``FitResult.undrawable`` lists characters the bundled font has no glyph
  for (a name in CJK script): the PDF would print "?" for them, so the
  caller ships the Word file alone.

Everything here is CPU-only and in-process: no network, no browser, no LLM.
"""
