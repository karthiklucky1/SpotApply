# ── Tiers ────────────────────────────────────────────────────────────────────

@dataclass(frozen=True)
class Tier:
    """One layout density. Sizes in points, margins/indent in inches.

    ``line_spacing`` is Word's "multiple" line spacing (1.15 is what the
    python-docx template's docDefaults give every paragraph today).
    """
    name: str
    body_pt: float
    h1_pt: float
    h2_pt: float
    h3_pt: float
    margin_in: float
    line_spacing: float
    para_after_pt: float
    bullet_after_pt: float
    h1_after_pt: float
    h2_before_pt: float
    h2_after_pt: float
    h3_before_pt: float
    h3_after_pt: float
    bullet_indent_in: float = 0.25

    @property
    def margin_pt(self) -> float:
        return self.margin_in * 72.0

    @property
    def bullet_indent_pt(self) -> float:
        return self.bullet_indent_in * 72.0


MIN_BODY_PT = 9.5
MIN_MARGIN_IN = 0.5

TIERS: tuple[Tier, ...] = (
    # T0 = the current Word export (_set_ats_safe_styles): 11/14/12/11pt,
    # 0.75in margins, Normal after 2pt, bullets after 1pt, H1 after 4pt,
    # H2 6/2pt, H3 4/1pt, 1.15 line spacing from the template's docDefaults.
    Tier("T0", 11.0, 14.0, 12.0, 11.0, 0.75, 1.15, 2.0, 1.0, 4.0, 6.0, 2.0, 4.0, 1.0),
    Tier("T1", 10.5, 13.5, 11.5, 10.5, 0.6, 1.1, 2.0, 1.0, 3.0, 5.0, 2.0, 3.0, 1.0),
    Tier("T2", 10.0, 13.0, 11.0, 10.0, 0.5, 1.05, 1.5, 0.5, 2.0, 4.0, 1.5, 2.0, 0.5),
    Tier("T3", 9.5, 12.5, 10.5, 9.5, 0.5, 1.0, 1.0, 0.0, 2.0, 3.0, 1.0, 2.0, 0.0),
)


def _tier(t: Union[Tier, int]) -> Tier:
    if isinstance(t, Tier):
        return t
    return TIERS[int(t)]


# ── Markdown -> blocks (the _md_to_docx mapping) ─────────────────────────────

@dataclass(frozen=True)
class Run:
    text: str
    bold: bool = False
    italic: bool = False


@dataclass(frozen=True)
class Block:
    """One rendered paragraph.

    kind: ``name`` (# , Heading 1), ``header`` (Normal line before the first
    section), ``section`` (## , Heading 2), ``subhead`` (### , Heading 3),
    ``bullet`` (- / * , List Bullet) or ``para`` (Normal).
    ``line_no`` indexes ``md.splitlines()`` so a trim removes exactly that line.
    """
    kind: str
    runs: tuple[Run, ...]
    line_no: int
    raw: str

    @property
    def text(self) -> str:
        return "".join(r.text for r in self.runs)


_INLINE_RE = re.compile(r"(\*\*[^*\n]+\*\*|\*[^*\n]+\*)")
_HR_RE = re.compile(r"^[-*_ ]+$")


def _runs(text: str) -> tuple[Run, ...]:
    """``tailor._add_formatted_run``'s split, as data."""
    out: list[Run] = []
    for part in _INLINE_RE.split(text):
        if not part:
            continue
        if part.startswith("**") and part.endswith("**") and len(part) > 4:
            out.append(Run(part[2:-2], bold=True))
        elif part.startswith("*") and part.endswith("*") and len(part) > 2:
            out.append(Run(part[1:-1], italic=True))
        else:
            out.append(Run(part))
    return tuple(out)


def parse_md(md: str) -> list[Block]:
    """Markdown resume -> blocks, line for line as ``_md_to_docx`` maps it.

    Skipped exactly as there: blank lines, code fences, horizontal rules.
    Lines before the first "## " that are not headings or bullets are
    ``header`` (contact line, headline); after it they are ``para``.
    """
    blocks: list[Block] = []
    seen_section = False
    for i, line in enumerate((md or "").splitlines()):
        s = line.strip()
        if not s or s.startswith("```"):
            continue
        if _HR_RE.match(s) and len(s) >= 3:
            continue
        if s.startswith("# "):
            kind, body = "name", s[2:].strip()
        elif s.startswith("## "):
            kind, body = "section", s[3:].strip()
            seen_section = True
        elif s.startswith("### "):
            kind, body = "subhead", s[4:].strip()
        elif s.startswith("- ") or s.startswith("* "):
            kind, body = "bullet", s[2:]
        else:
            kind, body = ("para" if seen_section else "header"), s
        blocks.append(Block(kind, _runs(body), i, s))
    return blocks


def resume_name(md: str) -> str:
    """The candidate's name as the resume states it (the first "# " line)."""
    for b in parse_md(md):
        if b.kind == "name":
            return b.text.strip()
    return ""


# ── Font metrics (fpdf2's own width rounding, so wraps match the PDF) ───────

_METRICS: dict[str, dict[int, int]] = {}
_METRICS_DEFAULT: dict[str, int] = {}
_METRICS_LOCK = threading.Lock()


def _widths(style: str) -> dict[int, int]:
    """codepoint -> advance in 1/1000 em, rounded exactly as fpdf2 rounds
    (``round(1000/upem * advance + 0.001)``) - the same numbers the PDF's /W
    array carries, so a line we measure is the line a viewer draws."""
    table = _METRICS.get(style)
    if table is not None:
        return table
    with _METRICS_LOCK:
        table = _METRICS.get(style)
        if table is not None:
            return table
        from fontTools.ttLib import TTFont

        font = TTFont(str(FONT_DIR / _FONT_FILES[style]), lazy=True)
        try:
            scale = 1000 / font["head"].unitsPerEm
            hmtx = font["hmtx"].metrics
            built: dict[int, int] = {}
            for cp, glyph in font.getBestCmap().items():
                w = hmtx[glyph][0]
                built[cp] = round(scale * (0 if w == 65535 else w) + 0.001)
            _METRICS_DEFAULT[style] = round(scale * hmtx[".notdef"][0] + 0.001)
        finally:
            font.close()
        _METRICS[style] = built
        return built


_SAFE_CACHE: dict[str, str] = {}
_PUNCT_FALLBACK = {
    "\t": " ",
    "\u2192": "->", "\u2190": "<-", "\u2194": "<->", "\u21d2": "=>",
    "\u2264": "<=", "\u2265": ">=", "\u2260": "!=", "\u2248": "~",
    "\u2713": "", "\u2714": "", "\u2717": "", "\u2605": "*", "\u2606": "*",
    "\u25cf": _BULLET, "\u25a0": _BULLET, "\u2023": _BULLET,
    "\u2043": "-", "\u2212": "-",
    # Carlito has no glyph for these; word processors and PDF copy-paste
    # produce them ("co\u2011founded", "5\u2032", "A\u2219B").
    "\u2010": "-", "\u2011": "-", "\u2032": "'", "\u2035": "'",
    "\u2219": "\u00b7", "\u2027": "\u00b7", "\u2236": ":",
    # Math symbols a LaTeX resume's PDF text carries ($\sim$40\% -> "\u223c40%",
    # \cdot and \ast separators, \langle/\rangle, long arrows).
    "\u223c": "~", "\u2243": "~", "\u2245": "~", "\u22c5": "\u00b7", "\u2217": "*",
    "\u2223": "|", "\u2218": "\u25e6", "\u2981": _BULLET, "\u22c4": "\u00b7",
    "\u21d4": "<=>", "\u27e8": "<", "\u27e9": ">", "\u27f5": "<-", "\u27f6": "->",
    "\u27f9": "=>", "\u2208": "in",
    # Separators and bullets from templates and CJK input methods.
    "\u25ba": _BULLET, "\u25b8": _BULLET, "\u276f": "\u203a", "\u203b": "*",
    "\u3002": ".", "\u3001": ",", "\u301c": "~", "\u300c": '"', "\u300d": '"',
    "\u3010": "[", "\u3011": "]", "\u300a": "\u00ab", "\u300b": "\u00bb",
    # Currency signs Carlito lacks: the amount must keep its currency.
    "\u20ba": "TRY ", "\u20bd": "RUB ", "\u20bf": "BTC ",
}
# A dash, quote, space or bracket the font lacks is still one; other
# punctuation and math symbols without a stand-in are decoration (dropped).
_CATEGORY_FALLBACK = {"Pd": "-", "Pi": "'", "Pf": "'", "Zs": " ", "Ps": "(", "Pe": ")",
                      "Pc": "_", "Po": "", "Sm": "", "Sk": "", "So": "",
                      "Cs": "", "Co": "", "Cn": "", "Me": ""}
# Invisible in Word, but a font that has a glyph for them would draw one.
_INVISIBLE = {ord(c): None for c in "\u00ad\u200b\u200c\u200d\u2060\ufeff"}
# Characters drawn as UNDRAWABLE for want of a glyph: letters, digits and
# currency signs, i.e. resume content (a name in CJK script). Recorded here,
# not inferred from the drawn text, because "?" is also a legitimate result
# (U+FF1F, the fullwidth question mark, folds to it).
_NO_GLYPH: set[str] = set()
UNDRAWABLE = "?"


def _safe_char(ch: str, cmap: dict[int, int]) -> str:
    if ord(ch) in cmap:
        return ch
    cached = _SAFE_CACHE.get(ch)
    if cached is not None:
        return cached
    out: Optional[str] = None
    if ch in _PUNCT_FALLBACK and all(ord(c) in cmap for c in _PUNCT_FALLBACK[ch]):
        out = _PUNCT_FALLBACK[ch]
    elif unicodedata.category(ch) in ("Cc", "Cf", "Zl", "Zp", "Mn"):
        out = " " if ch in "\n\r\v\f\u2028\u2029" else ""
    if out is None:
        nfkc = unicodedata.normalize("NFKC", ch)
        if nfkc != ch and nfkc and all(ord(c) in cmap for c in nfkc):
            out = nfkc
    if out is None:
        folded = unicodedata.normalize("NFKD", ch).encode("ascii", "ignore").decode()
        if folded:
            out = folded
    if out is None:
        # A pictograph (emoji, dingbat), a math sign or a stray mark carries
        # no resume content; a dash, quote, space or bracket keeps its role.
        out = _CATEGORY_FALLBACK.get(unicodedata.category(ch))
    if out is None:
        # A letter, digit or currency sign (e.g. a CJK name) is content this
        # font cannot draw.
        out = UNDRAWABLE
        _NO_GLYPH.add(ch)
        log.debug("resume pdf: no glyph for U+%04X", ord(ch))
    _SAFE_CACHE[ch] = out
    return out


def undrawable_chars(text: str) -> list[str]:
    """Distinct characters of ``text`` the PDF would print as "?": letters,
    digits or currency signs the bundled font has no glyph or stand-in for
    (a name in CJK script). Symbols and punctuation never count - they are
    drawn as a stand-in or dropped."""
    cmap = _widths("")
    text = unicodedata.normalize("NFC", text or "").translate(_INVISIBLE)
    out: list[str] = []
    for c in dict.fromkeys(text):
        if ord(c) in cmap:
            continue
        _safe_char(c, cmap)
        if c in _NO_GLYPH:
            out.append(c)
    return out


def _pdf_text(text: str) -> str:
    """Text the bundled font can draw. Carlito covers Latin (accents, smart
    quotes, bullets, dashes), Greek and Cyrillic; anything else degrades to
    its closest drawable form instead of an empty box or an exception."""
    cmap = _widths("")
    text = unicodedata.normalize("NFC", text).translate(_INVISIBLE)
    if all(ord(c) in cmap for c in text):
        return text
    return "".join(_safe_char(c, cmap) for c in text)


def text_width(text: str, style: str, size: float) -> float:
    """Advance width in points of ``text`` in Carlito ``style`` at ``size``."""
    table = _widths(style)
    default = _METRICS_DEFAULT.get(style, 0)
    return sum(table.get(ord(c), default) for c in text) * size * 0.001


# ── Layout ───────────────────────────────────────────────────────────────────

_HEADING_KINDS = ("name", "section", "subhead")


@dataclass
class _Laid:
    block: Block
    size: float
    lh: float
    before: float
    after: float
    color: tuple[int, int, int]
    x0: float                 # left edge of the text, relative to the margin
    bullet: bool
    rule: bool
    lines: list[list[tuple[float, str, str]]] = field(default_factory=list)

    @property
    def height(self) -> float:
        return self.lh * len(self.lines) + (_RULE_PAD_PT if self.rule else 0.0)


def _style_of(kind: str, tier: Tier):
    """(size, before, after, color, bullet, rule) - the Word styles' values."""
    if kind == "name":
        return tier.h1_pt, 0.0, tier.h1_after_pt, _DARK, False, False
    if kind == "section":
        return tier.h2_pt, tier.h2_before_pt, tier.h2_after_pt, _DARK, False, True
    if kind == "subhead":
        return tier.h3_pt, tier.h3_before_pt, tier.h3_after_pt, _DARK, False, False
    if kind == "bullet":
        return tier.body_pt, 0.0, tier.bullet_after_pt, _BODY, True, False
    return tier.body_pt, 0.0, tier.para_after_pt, _BODY, False, False


def _wrap(chars: list[tuple[str, str]], size: float, avail: float) -> list[list[tuple[float, str, str]]]:
    """Greedy word wrap over (char, style) pairs, the way Word breaks lines:
    at spaces (dropped at the break) and after a hyphen inside a word; a word
    wider than the line is split by characters. Returns lines of
    (x offset, text, style) segments."""
    tables = {s: _widths(s) for s in {st for _, st in chars}}
    k = size * 0.001

    def w(seq) -> float:
        return sum(tables[st].get(ord(c), _METRICS_DEFAULT.get(st, 0)) for c, st in seq) * k

    # Split into (spaces, word) chunks; a hyphen between two alphanumerics
    # ends a chunk with no space after it (Word's break-after-hyphen).
    chunks: list[tuple[list, list]] = []
    i, n = 0, len(chars)
    while i < n:
        j = i
        while j < n and chars[j][0] == " ":
            j += 1
        m = j
        while m < n and chars[m][0] != " ":
            m += 1
            if (chars[m - 1][0] == "-" and m < n and chars[m][0].isalnum()
                    and m - 2 >= j and chars[m - 2][0].isalnum()):
                break
        chunks.append((chars[i:j], chars[j:m]))
        i = m

    lines: list[list[tuple[str, str]]] = []
    cur: list[tuple[str, str]] = []
    cur_w = 0.0
    for spaces, word in chunks:
        if not word:
            continue  # trailing spaces never take width
        sw, ww = w(spaces), w(word)
        if cur and cur_w + sw + ww <= avail + _EPS:
            cur.extend(spaces)
            cur.extend(word)
            cur_w += sw + ww
            continue
        if cur:
            lines.append(cur)
            cur, cur_w = [], 0.0
        if ww <= avail + _EPS:
            cur, cur_w = list(word), ww
            continue
        for pair in word:  # longer than a whole line (a URL): break anywhere
            cw = w([pair])
            if cur and cur_w + cw > avail + _EPS:
                lines.append(cur)
                cur, cur_w = [], 0.0
            cur.append(pair)
            cur_w += cw
    if cur or not lines:
        lines.append(cur)

    out: list[list[tuple[float, str, str]]] = []
    for line in lines:
        segs: list[tuple[float, str, str]] = []
        x = 0.0
        buf, buf_style, buf_x = "", None, 0.0
        for c, st in line:
            if st != buf_style:
                if buf:
                    segs.append((buf_x, buf, buf_style))
                buf, buf_style, buf_x = "", st, x
            buf += c
            x += tables[st].get(ord(c), _METRICS_DEFAULT.get(st, 0)) * k
        if buf:
            segs.append((buf_x, buf, buf_style))
        out.append(segs)
    return out


def _lay(block: Block, tier: Tier) -> _Laid:
    size, before, after, color, bullet, rule = _style_of(block.kind, tier)
    heading = block.kind in _HEADING_KINDS
    chars: list[tuple[str, str]] = []
    for r in block.runs:
        st = "B" if (heading or r.bold) else ("I" if r.italic else "")
        chars.extend((c, st) for c in _pdf_text(r.text))
    x0 = tier.bullet_indent_pt if bullet else 0.0
    avail = PAGE_W_PT - 2 * tier.margin_pt - x0
    laid = _Laid(block, size, size * LINE_FACTOR * tier.line_spacing, before, after,
                 color, x0, bullet, rule)
    laid.lines = _wrap(chars, size, avail)
    return laid


def _gap(prev: Optional[_Laid], cur: _Laid) -> float:
    """Space between two paragraphs, as Word computes it: space after +
    space before, except between two List Bullet paragraphs, whose style
    carries contextualSpacing (no space between same-style paragraphs)."""
    if prev is None:
        return cur.before
    if prev.bullet and cur.bullet:
        return 0.0
    return prev.after + cur.before


@dataclass
class _Placed:
    laid: _Laid
    line: int          # index into laid.lines; -1 = the section rule
    y: float           # top of the line box (or the rule's y)


def _paginate(laid: list[_Laid], tier: Tier, reserve: float = 0.0) -> list[list[_Placed]]:
    """Place lines on Letter pages. A line that would cross the bottom margin
    (raised by ``reserve`` points) starts a new page; a heading is kept with
    the first line after it."""
    top = tier.margin_pt
    bottom = PAGE_H_PT - tier.margin_pt - reserve
    pages: list[list[_Placed]] = [[]]
    y = top
    prev: Optional[_Laid] = None
    for idx, lb in enumerate(laid):
        y += _gap(prev, lb)
        if lb.block.kind in _HEADING_KINDS and idx + 1 < len(laid) and y > top + _EPS:
            nxt = laid[idx + 1]
            need = lb.height + _gap(lb, nxt) + nxt.lh
            if y + need > bottom + _EPS:
                pages.append([])
                y = top
        for li in range(len(lb.lines)):
            if y + lb.lh > bottom + _EPS and y > top + _EPS:
                pages.append([])
                y = top
            pages[-1].append(_Placed(lb, li, y))
            y += lb.lh
        if lb.rule:
            pages[-1].append(_Placed(lb, -1, y + _RULE_GAP_PT + _RULE_W_PT / 2))
            y += _RULE_PAD_PT
        prev = lb
    return pages


class _LayoutCache:
    """Wrapped lines per (block, tier) so trims re-paginate without re-wrapping."""

    def __init__(self) -> None:
        self._d: dict[tuple[int, str], _Laid] = {}

    def lay(self, blocks: list[Block], tier: Tier) -> list[_Laid]:
        out = []
        for b in blocks:
            key = (b.line_no, tier.name)
            laid = self._d.get(key)
            if laid is None:
                laid = self._d[key] = _lay(b, tier)
            out.append(laid)
        return out


def layout_pages(md: str, tier: Union[Tier, int] = 0) -> int:
    """How many Letter pages ``md`` takes at ``tier`` (no PDF produced)."""
    t = _tier(tier)
    return len(_paginate([_lay(b, t) for b in parse_md(md)], t))


def word_reserve_pt(tier: Union[Tier, int]) -> float:
    """Spare space a fitting layout must leave at the bottom of the page: one
    body line at ``tier``. Word wraps with its own engine (kerning, its own
    justification of a line that is a hair too long); without this margin a
    PDF that fills its page exactly can become a two-page .docx."""
    t = _tier(tier)
    return t.body_pt * LINE_FACTOR * t.line_spacing


