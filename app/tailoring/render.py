# OPC package parts (relationships, content types) are flat lists of empty
# elements; removing one is a text edit, no XML parser (or lxml import) needed.
_REL_RE = re.compile(rb"<Relationship\b[^>]*?(?:/>|>\s*</Relationship>)")
_OVERRIDE_RE = re.compile(rb"<Override\b[^>]*?(?:/>|>\s*</Override>)")


def _attr(el: bytes, name: bytes) -> str:
    m = re.search(rb"\b" + name + rb"\s*=\s*([\"'])(.*?)\1", el)
    return m.group(2).decode("utf-8", "replace") if m else ""


def _drop_rels(xml: bytes, type_suffix: str) -> tuple[bytes, list[str]]:
    """Remove relationships whose Type ends with ``type_suffix``; return the
    new XML and the removed targets."""
    targets: list[str] = []

    def repl(m: re.Match) -> bytes:
        if _attr(m.group(0), b"Type").endswith(type_suffix):
            targets.append(_attr(m.group(0), b"Target"))
            return b""
        return m.group(0)

    out = _REL_RE.sub(repl, xml)
    return (out, targets) if targets else (xml, [])


def _drop_overrides(xml: bytes, part_names: tuple[str, ...]) -> bytes:
    def repl(m: re.Match) -> bytes:
        return b"" if _attr(m.group(0), b"PartName").lstrip("/") in part_names else m.group(0)

    return _OVERRIDE_RE.sub(repl, xml)


