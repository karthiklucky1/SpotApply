def _fresh_revision_ids(payload: dict[str, bytes]) -> None:
    """Replace the template's revision-session ids and document id with
    random ones, consistently across every word/*.xml part.

    python-docx copies its template's parts verbatim, so every file it writes
    carries the SAME ``w:rsidRoot``/``w:rsid`` list and ``w14:docId`` - a
    fingerprint shared by all of them. Every id in any part is remapped,
    including ones settings.xml never declares (the template's styles.xml
    carries one on its Header/Footer styles). Word's own ids are random
    24-bit values, written as 8 hex digits.
    """
    parts = [n for n in payload if n.startswith("word/") and n.endswith(".xml")]
    old = list(dict.fromkeys(
        m.group(2).upper()
        for name in parts
        for rx in (_RSID_DECL_RE, _RSID_ATTR_RE)
        for m in rx.finditer(payload[name])))
    fresh: dict[bytes, bytes] = {}
    for o in old:
        while True:
            new = ("00%06X" % int.from_bytes(os.urandom(3), "big")).encode()
            if new not in fresh.values() and new not in old:
                break
        fresh[o] = new

    def rsid(m: re.Match) -> bytes:
        return m.group(1) + fresh.get(m.group(2).upper(), m.group(2)) + m.group(3)

    def docid(m: re.Match) -> bytes:
        val = ("%08X" % (int.from_bytes(os.urandom(4), "big") & 0x7FFFFFFF)).encode()
        return m.group(1) + val + m.group(3)

    for name in parts:
        xml = payload[name]
        if fresh:
            xml = _RSID_ATTR_RE.sub(rsid, xml)
            xml = _RSID_DECL_RE.sub(rsid, xml)
        xml = _DOCID_RE.sub(docid, xml)
        payload[name] = xml


def _scrub_docx_bytes(data: bytes, *, author: str = "", title: str = "") -> bytes:
    """Rewrite a .docx so its package names the candidate, not the software.

    * docProps/core.xml: rewritten - creator/lastModifiedBy = ``author``,
      title, revision 1, created/modified = now; no subject, keywords,
      description ("generated by python-docx") or category.
    * docProps/app.xml: minimal - no Application ("Microsoft Macintosh
      Word"), AppVersion, Company, Template or the template's static counts.
    * the template's thumbnail (identical in every python-docx file) and its
      bibliography customXml part (a fixed GUID) are removed with their
      relationships and content-type overrides.
    """
    now = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    a = _xml_escape(_docx_text(author or "").strip())
    t = _xml_escape(_docx_text(title or "").strip())
    core = _CORE_XML.format(
        title=f"<dc:title>{t}</dc:title>" if t else "",
        creator=f"<dc:creator>{a}</dc:creator>" if a else "",
        last=f"<cp:lastModifiedBy>{a}</cp:lastModifiedBy>" if a else "",
        now=now,
    ).encode("utf-8")

    src = zipfile.ZipFile(io.BytesIO(data))
    names = src.namelist()
    payload = {n: src.read(n) for n in names}
    src.close()

    dropped: set[str] = set()
    if "_rels/.rels" in payload:
        payload["_rels/.rels"], targets = _drop_rels(payload["_rels/.rels"], _THUMBNAIL_REL)
        dropped.update(x.lstrip("/") for x in targets)
    doc_rels = "word/_rels/document.xml.rels"
    if doc_rels in payload:
        payload[doc_rels], targets = _drop_rels(payload[doc_rels], _CUSTOMXML_REL)
        if targets:
            dropped.update(n for n in names if n.startswith("customXml/"))
    dropped &= set(names)
    if "[Content_Types].xml" in payload and dropped:
        payload["[Content_Types].xml"] = _drop_overrides(
            payload["[Content_Types].xml"], tuple(sorted(dropped)))
    if "docProps/core.xml" in payload:
        payload["docProps/core.xml"] = core
    if "docProps/app.xml" in payload:
        payload["docProps/app.xml"] = _APP_XML.encode("utf-8")
    _fresh_revision_ids(payload)

    stamp = datetime.now().timetuple()[:6]
    out = io.BytesIO()
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as zf:
        for n in names:
            if n in dropped:
                continue
            info = zipfile.ZipInfo(n, date_time=stamp)
            info.compress_type = zipfile.ZIP_DEFLATED
            zf.writestr(info, payload[n])
    return out.getvalue()


def scrub_docx_metadata(path: Union[str, Path], *, author: str = "", title: str = "") -> Path:
    """Scrub generator traces from an existing .docx in place (see
    ``_scrub_docx_bytes``). Works on any python-docx output, including
    ``tailor._md_to_docx``'s."""
    p = Path(path)
    _atomic_write(p, _scrub_docx_bytes(p.read_bytes(), author=author, title=title))
    return p


# ── File names ───────────────────────────────────────────────────────────────

_CORP_SUFFIXES = frozenset({
    "inc", "incorporated", "llc", "llp", "ltd", "limited", "corp", "corporation",
    "gmbh", "plc", "co", "lp", "sa", "ag", "bv",
})


# Letters NFKD does not decompose to ASCII (they are letters of their own,
# not an ASCII letter plus an accent), spelled the way names conventionally
# transliterate them.
_TRANSLIT = str.maketrans({
    "Ł": "L", "ł": "l", "ß": "ss", "ẞ": "SS", "Ø": "O", "ø": "o", "Æ": "AE", "æ": "ae",
    "Œ": "OE", "œ": "oe", "Đ": "D", "đ": "d", "Ð": "D", "ð": "d", "Þ": "Th", "þ": "th",
    "ı": "i", "Ħ": "H", "ħ": "h", "Ŀ": "L", "ŀ": "l", "Ŧ": "T", "ŧ": "t", "ĸ": "k",
    "\u2019": "'", "\u02bc": "'", "\u2018": "'",
})
_APOSTROPHES_ETC_RE = re.compile(r"['`.&]")


def _ascii(s: str) -> str:
    s = (s or "").translate(_TRANSLIT)
    return unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode("ascii")


def _fold(s: str) -> str:
    """ASCII fold + drop apostrophes/periods/ampersands + non-alnum runs -> _."""
    s = _APOSTROPHES_ETC_RE.sub("", _ascii(s))
    return re.sub(r"[^A-Za-z0-9]+", "_", s).strip("_")


def _name_part(s: str) -> str:
    # Judged before transliteration: an all-caps "WEIß" keeps a lowercase ß
    # (the conventional caps spelling) that would otherwise become "ss".
    letters = [c for c in (s or "") if c.isalpha() and c != "ß"]
    plain = _ascii(s)
    if len(letters) >= 2 and all(c.isupper() for c in letters):
        # "PRIYA RAMANATHAN" as the resume heading writes it -> Priya;
        # capitalised per piece BEFORE the apostrophe goes: O'BRIEN -> OBrien
        plain = re.sub(r"[A-Za-z]+", lambda m: m.group(0).capitalize(), plain)
    return _fold(plain)[:40].strip("_")


def document_filename(first: str, last: str, company: str, kind: str = "Resume",
                      ext: str = "docx") -> str:
    """``First_Last_Resume.docx`` - the owner's naming rule; tailoring passes
    a blank ``company`` (the owner dropped it from the name, 2026-10-08).

    Accents fold to ASCII ("José" -> "Jose", "Łukasz" -> "Lukasz", "Weiß" ->
    "Weiss"), apostrophes/periods/& vanish ("O'BRIEN" -> "OBrien"), other
    punctuation and spaces become one underscore. A company, when given,
    loses trailing corporate suffixes (Inc, LLC, Ltd, Corp, GmbH, PLC, Co, LP,
    SA, AG, BV, ...) and is capped at 40 characters; a blank one drops its
    segment. Blank names fall back to "Candidate". ``kind`` is "Resume" or
    "Cover_Letter".
    """
    name = "_".join(p for p in (_name_part(first), _name_part(last)) if p) or "Candidate"

    toks = [t for t in _fold(company).split("_") if t]
    while len(toks) > 1 and toks[-1].lower() in _CORP_SUFFIXES:
        toks.pop()
    comp = "_".join(toks)[:40].strip("_")

    kind_part = _fold(kind) or "Resume"
    ext_part = re.sub(r"[^A-Za-z0-9]", "", ext or "").lower()
    stem = "_".join(p for p in (name, comp, kind_part) if p)
    return f"{stem}.{ext_part}" if ext_part else stem


