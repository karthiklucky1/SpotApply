def _subset_tag(seed: bytes, font_name: bytes) -> bytes:
    for salt in range(64):
        digest = hashlib.sha256(seed + b"\0" + font_name + bytes([salt])).digest()
        tag = bytes(65 + (x % 26) for x in digest[:6])
        if not find_generator_markers(tag):  # six random capitals can spell "GPT"
            return tag
    return b"XQZKVJ"  # unreachable in practice


_SUBSET_RE = re.compile(rb"/MPDFAA\+([A-Za-z0-9\-]+)")


def _retag_subsets(pdf: bytes) -> bytes:
    """fpdf2 prefixes every embedded subset with the constant tag ``MPDFAA+``
    - a signature of the library. A subset tag is just six capitals (ISO
    32000 9.6.4), so each font gets one derived from the document's own
    content: same length (the xref offsets stay valid), no constant."""
    seed = hashlib.sha256(pdf).digest()
    return _SUBSET_RE.sub(lambda m: b"/" + _subset_tag(seed, m.group(1)) + b"+" + m.group(1), pdf)


def outside_streams(pdf: bytes) -> bytes:
    """The PDF minus its (binary) stream payloads: object dictionaries, the
    Info dict, the trailer - where a generator would leave its name. (A
    compressed payload is noise; three random bytes in it can read "GPT".)"""
    return re.sub(rb">>\s*stream\r?\n.*?endstream", b">> stream endstream", pdf, flags=re.S)


def find_generator_markers(data: bytes) -> list[str]:
    """Generator/vendor markers present in ``data`` (case-insensitive)."""
    low = data.lower()
    return [m for m in GENERATOR_MARKERS if m.encode() in low]


def _rewrite_pdf_metadata(pdf: bytes, author: str, title: str) -> bytes:
    """Last-resort metadata rewrite (an fpdf2 that ignores an empty producer):
    drop the Info dict and any XMP packet, write only author/title/date."""
    from pypdf import PdfReader, PdfWriter
    from pypdf.generic import NameObject

    writer = PdfWriter(clone_from=PdfReader(io.BytesIO(pdf)))
    writer.metadata = None
    root = getattr(writer, "root_object", None) or writer._root_object
    if NameObject("/Metadata") in root:
        del root[NameObject("/Metadata")]
    meta = {"/CreationDate": datetime.now(timezone.utc).strftime("D:%Y%m%d%H%M%SZ")}
    if author:
        meta["/Author"] = author
    if title:
        meta["/Title"] = title
    writer.add_metadata(meta)
    out = io.BytesIO()
    writer.write(out)
    return out.getvalue()


def _draw(pages: list[list[_Placed]], tier: Tier, *, author: str, title: str) -> bytes:
    from fpdf import FPDF

    pdf = FPDF(unit="pt", format="letter")
    pdf.set_auto_page_break(False)
    pdf.set_margins(tier.margin_pt, tier.margin_pt, tier.margin_pt)
    for style, fname in _FONT_FILES.items():
        pdf.add_font(_FONT_FAMILY, style, str(FONT_DIR / fname))
    # Metadata: the candidate is the author; nothing names the software.
    pdf.set_creator("")
    pdf.set_producer("")
    if author:
        pdf.set_author(author)
    if title:
        pdf.set_title(title)
    pdf.set_creation_date(datetime.now(timezone.utc))

    left = tier.margin_pt
    for page in pages:
        pdf.add_page()
        for placed in page:
            lb = placed.laid
            if placed.line < 0:
                pdf.set_draw_color(*_RULE)
                pdf.set_line_width(_RULE_W_PT)
                pdf.line(left, placed.y, PAGE_W_PT - tier.margin_pt, placed.y)
                continue
            # Extra leading of a >1.0 multiple sits above the text, as in Word.
            baseline = placed.y + lb.lh - _WIN_DESCENT * lb.size
            pdf.set_text_color(*lb.color)
            if lb.bullet and placed.line == 0:
                pdf.set_font(_FONT_FAMILY, "", lb.size)
                pdf.text(left, baseline, _BULLET)
            for dx, seg, style in lb.lines[placed.line]:
                pdf.set_font(_FONT_FAMILY, style, lb.size)
                pdf.text(left + lb.x0 + dx, baseline, seg)
    data = _retag_subsets(bytes(pdf.output()))
    # A candidate may be NAMED Claude; only flag what the document's own
    # author/title do not explain.
    own = f"{author} {title}".lower()
    if [m for m in find_generator_markers(outside_streams(data)) if m not in own]:
        data = _rewrite_pdf_metadata(data, author, title)
    return data


def render_pdf(md: str, tier: Union[Tier, int] = 0, *, author: str = "", title: str = "") -> bytes:
    """Render the markdown resume to PDF bytes at ``tier``.

    Letter, single column, real (selectable, ATS-parseable) text in the
    bundled Carlito font; no images, no tables. Metadata: Author = ``author``,
    Title = ``title``, a creation date, nothing else.
    """
    t = _tier(tier)
    pages = _paginate([_lay(b, t) for b in parse_md(md)], t)
    return _draw(pages, t, author=author, title=title)


def page_count(pdf_bytes: bytes) -> int:
    """Pages in a PDF, read back with pypdf (not from our own layout)."""
    from pypdf import PdfReader

    return len(PdfReader(io.BytesIO(pdf_bytes)).pages)


